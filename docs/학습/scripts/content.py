def h1(t): DOC.append(dict(t="h1", text=t))
def h2(t): DOC.append(dict(t="h2", text=t))
def h3(t): DOC.append(dict(t="h3", text=t))
def p(*ts): DOC.extend(dict(t="p", text=t) for t in ts)
def ul(*items): DOC.append(dict(t="ul", items=list(items)))
def ol(*items): DOC.append(dict(t="ol", items=list(items)))
def pb(): DOC.append(dict(t="pb"))
def img(name, cap, w=6.2): DOC.append(dict(t="img", name=name, cap=cap, w=w))
def table(rows, widths=None, small=False, hdr=True): DOC.append(dict(t="table", rows=rows, widths=widths, small=small, hdr=hdr))
def boxx(kind, title, *items): DOC.append(dict(t="box", kind=kind, title=title, items=list(items)))


def eq(tex, note=None, size=13):
    """수식 1줄을 PNG로 (matplotlib mathtext). $가 없으면 전체를 수식으로 감쌈. 한글은 $ 밖에만."""
    _n[0] += 1; name = f"eq{_n[0]:03d}"; s = tex if "$" in tex else f"${tex}$"
    f = plt.figure(figsize=(0.01, 0.01)); f.text(0, 0, s, fontsize=size)
    f.savefig(EQ / f"{name}.png", dpi=220, bbox_inches="tight", pad_inches=0.04, facecolor="white", transparent=False); plt.close(f)
    from PIL import Image
    w, h = Image.open(EQ / f"{name}.png").size
    DOC.append(dict(t="eq", name=name, w=w / 220, h=h / 220, note=note))


def steps(*pairs):
    """단계별 수식: (설명, 수식[, 보충]) 묶음 → '단계 k' 문단 + 수식."""
    for k, pr in enumerate(pairs, 1):
        txt, tex = pr[0], pr[1]
        DOC.append(dict(t="p", text=f"**단계 {k}.** {txt}"))
        if tex:
            eq(tex)
        if len(pr) > 2 and pr[2]:
            DOC.append(dict(t="p", text=pr[2], muted=True))


